"""Generate pure Dart message references and the Flutter resolver from ARB.

Run after flutter gen-l10n. --check verifies committed generated files.
"""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ARB_DIR = ROOT / 'apps/fideflow_flutter/lib/l10n'


def outputs():
    template = json.loads((ARB_DIR / 'app_zh_Hans.arb').read_text(encoding='utf-8'))
    keys = {k for k in template if not k.startswith('@')}
    reserved = {'assert', 'break', 'case', 'catch', 'class', 'const', 'continue',
                'default', 'do', 'else', 'enum', 'extends', 'false', 'final',
                'finally', 'for', 'if', 'in', 'is', 'new', 'null', 'rethrow',
                'return', 'super', 'switch', 'this', 'throw', 'true', 'try',
                'var', 'void', 'while', 'with'}
    for key in keys:
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', key) or key in reserved:
            raise ValueError(f'Use a stable camelCase resource key: {key}')
    for locale in ('en',):
        translated = json.loads((ARB_DIR / f'app_{locale}.arb').read_text(encoding='utf-8'))
        if {k for k in translated if not k.startswith('@')} != keys:
            raise ValueError(f'Resource keys differ for {locale}')
        for key in keys:
            names = set(template.get('@' + key, {}).get('placeholders', {}))
            actual = set(re.findall(r'\{(\w+)(?:\}|,)', translated[key])) - {'other', 'one', 'zero'}
            if actual != names:
                raise ValueError(f'Placeholder mismatch: {locale}/{key}: {actual} != {names}')
    refs = ["// GENERATED by tooling/generate_ui_references.py. Do not edit.",
            "import 'ui_message.dart';", '',
            '/// Typed resource references for presentation-independent messages.',
            'abstract final class UiMessages {']
    resolver = ["// GENERATED by tooling/generate_ui_references.py. Do not edit.",
                "import 'package:fideflow_domain/domain.dart';",
                "import 'app_localizations.dart';", '',
                'String? resolveUiMessage(AppLocalizations copy, UiMessage message,',
                '    String Function(String) resolve) {',
                '  final args = message.arguments;',
                '  return switch (message.key) {']
    for key in sorted(keys):
        metadata = template.get('@' + key, {})
        placeholders = metadata.get('placeholders', {})
        if placeholders:
            params = ', '.join(f"{p.get('type', 'Object')} {name}" for name, p in placeholders.items())
            values = ', '.join(placeholders)
            refs.append(f"  static String {key}({params}) => UiMessage.format('{key}', [{values}]);")
            args = ', '.join(
                f'(args[{i}] as num).toInt()' if p.get('type') == 'int' else
                f'(args[{i}] as num).toDouble()' if p.get('type') == 'double' else
                f'resolve(args[{i}].toString())'
                for i, p in enumerate(placeholders.values()))
            resolver.append(f"    '{key}' when args.length == {len(placeholders)} => copy.{key}({args}),")
        else:
            refs.append(f"  static const {key} = '\\u001f{key}\\u001e';")
            resolver.append(f"    '{key}' => copy.{key},")
    refs.append('}')
    resolver.extend(['    _ => null,', '  };', '}'])
    native_keys = {'show': 'trayShow', 'play': 'play', 'pause': 'pause',
                   'previous': 'previousTrack', 'next': 'nextTrack',
                   'quit': 'quitFideflow', 'instanceLockFailed': 'instanceLockFailed'}
    native = ['// GENERATED by tooling/generate_ui_references.py. Do not edit.',
              '#pragma once', '', 'enum class UiLanguage { english, simplified };',
              'struct NativeUiLabels {']
    native += [f'  const wchar_t* {name};' for name in native_keys]
    native += ['};', 'inline NativeUiLabels NativeLabels(UiLanguage language) {', '  switch (language) {']
    for enum, locale in [('english', 'en'), ('simplified', 'zh_Hans')]:
        values = json.loads((ARB_DIR / f'app_{locale}.arb').read_text(encoding='utf-8'))
        native.append(f'    case UiLanguage::{enum}: return {{')
        native += ['      L' + json.dumps(values[key], ensure_ascii=False) + ',' for key in native_keys.values()]
        native.append('    };')
    native.extend(['  }', '  return NativeLabels(UiLanguage::simplified);', '}'])
    return {
        ARB_DIR / 'app_zh.arb': json.dumps({**template, '@@locale': 'zh'}, ensure_ascii=False, indent=2) + '\n',
        ROOT / 'packages/domain/lib/src/ui_messages.dart': '\n'.join(refs) + '\n',
        ARB_DIR / 'ui_message_resolver.dart': '\n'.join(resolver) + '\n',
        ROOT / 'apps/fideflow_flutter/windows/runner/localization_resources.h': '\n'.join(native) + '\n',
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            existing = path.read_text(encoding='utf-8') if path.exists() else ''
            def normalized(value):
                if path.suffix != '.dart': return value
                value = re.sub(r'//[^\n]*', '', value)
                tokens = re.findall(r"'(?:\\.|[^'])*'|[A-Za-z0-9_]+|[^\s]", value)
                return [t for i,t in enumerate(tokens) if not (t == ',' and i+1 < len(tokens) and tokens[i+1] in (')', '}', ']'))]
            if normalized(existing) != normalized(content):
                raise SystemExit(f'Regenerate {path.relative_to(ROOT)}')
        else:
            path.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
